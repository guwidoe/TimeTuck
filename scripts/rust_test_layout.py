"""Generate/validate Cargo test shards without moving original test sources."""
import argparse
import hashlib
import json
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MARKER = '# Generated test layout: python3 scripts/rust_test_layout.py --write\n'
SHARDS = 16
# Preserve crate-root lookups and isolate PID + module-local-counter fixtures.
STANDALONE = frozenset({
    'ordered_destination_regression',
    'owned_roster_cli_regression',
    'platform_configuration_cases', 'platform_configuration_regression',
    'solution_persistence_cases', 'solution_persistence_regression',
})


def generated(root=ROOT):
    tests = root / 'crates/solver/tests'
    originals = sorted(tests.glob('*.rs'))
    groups = {f'suite_{i:02}': [] for i in range(SHARDS)}
    for path in originals:
        if path.stem not in STANDALONE:
            index = int.from_bytes(hashlib.sha256(path.stem.encode()).digest()[:4], 'big') % SHARDS
            groups[f'suite_{index:02}'].append(path)
    wrappers, targets = {}, []
    for name, members in groups.items():
        if not members:
            continue
        relative = f'crates/solver/tests/shards/{name}.rs'
        wrappers[relative] = ('//! Generated by scripts/rust_test_layout.py; keep original files and identities.\n'
                              '// Fixtures intentionally retain separate module-local types and statics.\n'
                              '#![allow(clippy::duplicate_mod)]\n\n' +
                              ''.join(f'#[path = "../{p.name}"]\npub mod {p.stem};\n' for p in members))
        targets.append({'name': name, 'path': f'tests/shards/{name}.rs'})
    for path in originals:
        target = {'name': path.stem, 'path': f'tests/{path.name}'}
        if path.stem not in STANDALONE:
            target['test'] = False
        targets.append(target)
    block = MARKER
    for target in targets:
        block += '\n[[test]]\n' + ''.join(
            f'{k} = {json.dumps(v)}\n'
            for k, v in target.items())
    return block, wrappers, targets


def validate(root=ROOT):
    manifest = root / 'crates/solver/Cargo.toml'
    if not manifest.exists():
        return None
    text = manifest.read_text()
    if MARKER not in text:
        return None  # Original layout remains readable, including old logs.
    block, wrappers, targets = generated(root)
    data = tomllib.loads(text)
    actual = {str(p.relative_to(root)) for p in (root / 'crates/solver/tests/shards').glob('*.rs')}
    if (text.split(MARKER, 1)[1] != block[len(MARKER):] or
            data['package'].get('autotests') is not False or
            data.get('test') != targets or actual != set(wrappers) or
            any(not (root / p).exists() or (root / p).read_text() != value for p, value in wrappers.items())):
        raise ValueError('Test layout is stale. Run python3 scripts/rust_test_layout.py --write.')
    return targets


def integration_targets(root=ROOT):
    targets = validate(root)
    if targets is None:
        return [(p.stem, str(p.relative_to(root)))
                for p in sorted((root / 'crates/solver/tests').glob('*.rs'))]
    return [(t['name'], 'crates/solver/' + t['path']) for t in targets if t.get('test', True)]


def shard_origins(root=ROOT):
    """Only exact validated wrappers may attribute prefixed names to originals."""
    targets = validate(root)
    if targets is None:
        return {}
    _, wrappers, _ = generated(root)
    # Derive membership with the same stable partition, not a permissive regex
    # that could attribute arbitrary module prefixes to a known test file.
    import re
    return {path: {module: f'crates/solver/tests/{filename}'
                   for filename, module in re.findall(r'#\[path = "../(\w+\.rs)"\]\npub mod (\w+);', content)}
            for path, content in wrappers.items()}


def write(root=ROOT):
    manifest = root / 'crates/solver/Cargo.toml'
    base = manifest.read_text().split(MARKER, 1)[0].rstrip() + '\n\n'
    if 'autotests = false\n' not in base:
        base = base.replace('[package]\n', '[package]\nautotests = false\n', 1)
    block, wrappers, _ = generated(root)
    manifest.write_text(base + block)
    directory = root / 'crates/solver/tests/shards'
    directory.mkdir(exist_ok=True)
    for old in directory.glob('*.rs'):
        if str(old.relative_to(root)) not in wrappers:
            old.unlink()
    for path, content in wrappers.items():
        (root / path).write_text(content)
    validate(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate manifest entries and shard wrappers')
    args = parser.parse_args()
    if args.write:
        write()
    targets = integration_targets()
    print(f'{len(targets)} integration executables; original sources and explicit Cargo targets preserved.')


if __name__ == '__main__':
    main()
