use timetuck::*;
fn rows() -> Vec<Vec<&'static str>> {
    vec![vec!["a", "b", "c"], vec!["d", "e"], vec!["f"]]
}
fn view<'a>(rows: &'a [Vec<&'static str>]) -> SegmentedSlice<'a, &'static str> {
    SegmentedSlice::new(rows.iter().map(Vec::as_slice))
}
#[test]
fn move_elements_of_delegates() {
    let mut rows = rows();
    // Source gives inclusive end positions [1,3,5], then [2,4,5].
    repartition_lists(&mut rows, &[2, 2, 2]).unwrap();
    assert_eq!(rows, [vec!["a", "b"], vec!["c", "d"], vec!["e", "f"]]);
    repartition_lists(&mut rows, &[3, 2, 1]).unwrap();
    assert_eq!(rows, [vec!["a", "b", "c"], vec!["d", "e"], vec!["f"]]);
}
#[test]
fn complex_move_elements_of_delegates() {
    let expected: Vec<_> = ('a'..='v').collect();
    let mut rows = vec![
        expected[..3].to_vec(),
        expected[3..8].to_vec(),
        expected[8..13].to_vec(),
        expected[13..].to_vec(),
    ];
    repartition_lists(&mut rows, &[4, 10, 5, 3]).unwrap();
    assert_eq!(
        rows,
        [
            expected[..4].to_vec(),
            expected[4..14].to_vec(),
            expected[14..19].to_vec(),
            expected[19..].to_vec()
        ]
    );
    let v = SegmentedSlice::new(rows.iter().map(Vec::as_slice));
    assert_eq!(v.offsets().collect::<Vec<_>>(), [0, 4, 14, 19]);
    assert_eq!(rows.iter().map(Vec::len).collect::<Vec<_>>(), [4, 10, 5, 3]);
    repartition_lists(&mut rows, &[3, 5, 5, 9]).unwrap();
    assert_eq!(
        rows,
        [
            expected[..3].to_vec(),
            expected[3..8].to_vec(),
            expected[8..13].to_vec(),
            expected[13..].to_vec()
        ]
    );
    let v = SegmentedSlice::new(rows.iter().map(Vec::as_slice));
    assert_eq!(v.offsets().collect::<Vec<_>>(), [0, 3, 8, 13]);
    assert_eq!(rows.iter().map(Vec::len).collect::<Vec<_>>(), [3, 5, 5, 9]);
}
#[test]
fn size() {
    for (rows, n) in [
        (vec![], 0),
        (vec![vec![]], 0),
        (vec![vec!["a", "b", "c"]], 3),
        (vec![vec!["a", "b"], vec!["c"], vec!["d"]], 4),
    ] {
        assert_eq!(view(&rows).len(), n);
    }
}
#[test]
fn is_empty() {
    for (rows, empty) in [
        (vec![], true),
        (vec![vec![]], true),
        (vec![vec!["a", "b", "c"]], false),
        (vec![vec!["a", "b"], vec!["c"], vec!["d"]], false),
    ] {
        assert_eq!(view(&rows).is_empty(), empty);
    }
}
#[test]
fn contains() {
    let rows: Vec<Vec<_>> = rows()
        .into_iter()
        .map(|r| r.into_iter().map(Some).collect())
        .collect();
    let v = SegmentedSlice::new(rows.iter().map(Vec::as_slice));
    for value in ["a", "b", "c", "d", "e", "f"] {
        assert!(v.contains(&Some(value)));
    }
    assert!(!v.contains(&Some("g")));
    assert!(!v.contains(&None));
}
#[test]
fn iterator() {
    let rows = rows();
    assert_eq!(
        view(&rows).iter().copied().collect::<Vec<_>>(),
        ["a", "b", "c", "d", "e", "f"]
    );
}
#[test]
fn to_array() {
    let rows = rows();
    let array: Vec<_> = view(&rows).iter().cloned().collect();
    assert_eq!(array, ["a", "b", "c", "d", "e", "f"]);
}
#[test]
fn contains_all() {
    let rows = rows();
    let v = view(&rows);
    let all = ["a", "b", "c", "d", "e", "f"];
    // All subsets cover every subset generated by the source recursive helper.
    for mask in 0..64 {
        let mut subset: Vec<_> = all
            .iter()
            .enumerate()
            .filter(|(i, _)| mask & (1 << i) != 0)
            .map(|(_, v)| *v)
            .collect();
        assert!(subset.iter().all(|value| v.contains(value)));
        subset.push("g");
        assert!(!subset.iter().all(|value| v.contains(value)));
    }
}
fn repeated_rows() -> Vec<Vec<Option<&'static str>>> {
    rows()
        .into_iter()
        .cycle()
        .take(6)
        .map(|r| r.into_iter().map(Some).collect())
        .collect()
}
#[test]
fn index_of() {
    let rows = repeated_rows();
    let v = SegmentedSlice::new(rows.iter().map(Vec::as_slice));
    for (i, value) in ["a", "b", "c", "d", "e", "f"].into_iter().enumerate() {
        assert_eq!(v.position(&Some(value)), Some(i));
    }
    assert_eq!(v.position(&Some("g")), None);
    assert_eq!(v.position(&None), None);
}
#[test]
fn last_index_of() {
    let rows = repeated_rows();
    let v = SegmentedSlice::new(rows.iter().map(Vec::as_slice));
    for (i, value) in ["a", "b", "c", "d", "e", "f"].into_iter().enumerate() {
        assert_eq!(v.rposition(&Some(value)), Some(i + 6));
    }
    // Source intentionally checks indexOf here as well.
    assert_eq!(v.position(&Some("g")), None);
    assert_eq!(v.position(&None), None);
}
#[test]
fn sublist() {
    let mut rows = rows();
    let expected = ["a", "b", "c", "d", "e", "f"];
    let v = view(&rows);
    for from in 0..6 {
        for to in from..=6 {
            let sub = v.range(from..to).unwrap();
            assert_eq!(sub.len(), to - from);
            assert_eq!(sub.iter().copied().collect::<Vec<_>>(), expected[from..to]);
        }
    }
    let mut v = SegmentedSliceMut::new(rows.iter_mut().map(Vec::as_mut_slice));
    {
        let mut first = v.range_mut(0..3).unwrap();
        for (i, new) in ["v0", "v1", "v2"].into_iter().enumerate() {
            assert_eq!(first.replace(i, new), Some(expected[i]));
        }
    }
    assert_eq!(v.view().segment(0).unwrap(), ["v0", "v1", "v2"]);
    {
        let mut second = v.range_mut(3..6).unwrap();
        for (i, new) in ["v3", "v4", "v5"].into_iter().enumerate() {
            assert_eq!(second.replace(i, new), Some(expected[i + 3]));
        }
    }
    drop(v);
    assert_eq!(rows, [vec!["v0", "v1", "v2"], vec!["v3", "v4"], vec!["v5"]]);
}
